"""Writers for INCAR, KPOINTS and POTCAR.

The INCAR is a faithful rendering of ``config.vasp.incar`` -- nothing is added
except ``SYSTEM`` -- with a one-line explanation next to common tags so that a
beginner can read the file directly.

POTCAR files are licensed by VASP and must never be committed. They are
concatenated from the site's PAW library (``site.vasp.potcar_root``) and only their
identity (TITEL line, ENMAX, SHA-256) is recorded in the manifest.
"""

from __future__ import annotations

import hashlib
import re
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Dict, List, Mapping, Optional, Sequence, Tuple

#: One-line explanations written next to INCAR tags.
INCAR_GLOSSARY: Dict[str, str] = {
    "PREC": "precision preset (FFT grids); Accurate is recommended for energies",
    "ENCUT": "plane-wave cutoff in eV (basis-set size) - must be converged",
    "EDIFF": "electronic (SCF) convergence threshold in eV",
    "EDIFFG": "ionic stop criterion; negative = max force in eV/Angstrom",
    "ISMEAR": "smearing method: 1 Methfessel-Paxton (metals), 0 Gaussian (molecules)",
    "SIGMA": "smearing width in eV",
    "IBRION": "ionic algorithm: -1 none, 1 RMM-DIIS, 2 conjugate gradient, 5 finite differences",
    "NSW": "maximum number of ionic steps (0 = single-point calculation)",
    "ISIF": "what relaxes: 2 = ions only, 3 = ions + cell shape + volume",
    "POTIM": "step width (finite differences: displacement in Angstrom)",
    "NFREE": "number of displacements per degree of freedom (finite differences)",
    "NELM": "maximum number of SCF steps per ionic step",
    "ISPIN": "1 = non-spin-polarized, 2 = spin-polarized",
    "LASPH": "non-spherical PAW contributions inside spheres (recommended)",
    "LREAL": "real-space projection: Auto for large cells, .FALSE. for small cells",
    "ALGO": "electronic minimisation algorithm",
    "LWAVE": "write WAVECAR (large file)",
    "LCHARG": "write CHGCAR (large file)",
    "NCORE": "parallelisation: cores working on one band",
    "KPAR": "parallelisation: number of k-point groups",
}


def format_incar_value(value: object) -> str:
    """Format a Python value as VASP expects it."""

    if isinstance(value, bool):
        return ".TRUE." if value else ".FALSE."
    if isinstance(value, float):
        if value != 0 and (abs(value) < 1e-3 or abs(value) >= 1e5):
            mantissa, exponent = f"{value:.6E}".split("E")
            return f"{mantissa.rstrip('0').rstrip('.')}E{int(exponent)}"
        return repr(value)
    return str(value)


def render_incar(incar: Mapping[str, object], *, system_label: str) -> str:
    """Render an INCAR. Tag order: glossary order first (readability), then the rest."""

    ordered = [k for k in INCAR_GLOSSARY if k in incar] + sorted(k for k in incar if k not in INCAR_GLOSSARY)
    lines = [f"SYSTEM = {system_label}", ""]
    width = max(len(k) for k in ordered)
    for key in ordered:
        entry = f"{key.ljust(width)} = {format_incar_value(incar[key])}"
        note = INCAR_GLOSSARY.get(key)
        lines.append(f"{entry.ljust(width + 18)} ! {note}" if note else entry)
    lines.append("")
    lines.append("! Generated by `hsol prepare` from the run config; edit the campaign file, not this file.")
    return "\n".join(lines) + "\n"


def render_kpoints(grid: Sequence[int], style: str = "Gamma") -> str:
    """Automatic k-point mesh. Gamma-centred meshes preserve hexagonal symmetry."""

    return f"Automatic mesh ({style})\n0\n{style}\n  {grid[0]} {grid[1]} {grid[2]}\n  0 0 0\n"


# ----------------------------------------------------------------------------- POTCAR


@dataclass
class PotcarRecord:
    """Identity of one POTCAR dataset (safe to store in git)."""

    element: str
    label: str
    titel: Optional[str]
    enmax_eV: Optional[float]
    sha256: str
    source: str


class PotcarError(RuntimeError):
    """Raised when a POTCAR cannot be assembled."""


_TITEL_RE = re.compile(r"TITEL\s*=\s*(.+)")
_ENMAX_RE = re.compile(r"ENMAX\s*=\s*([0-9.]+)")


def read_potcar_identity(text: str) -> Tuple[Optional[str], Optional[float]]:
    titel = _TITEL_RE.search(text)
    enmax = _ENMAX_RE.search(text)
    return (titel.group(1).strip() if titel else None, float(enmax.group(1)) if enmax else None)


def assemble_potcar(
    potcar_root: Path, element_order: Sequence[str], labels: Mapping[str, str]
) -> Tuple[str, List[PotcarRecord]]:
    """Concatenate ``<potcar_root>/<label>/POTCAR`` in POSCAR species order."""

    if not potcar_root.is_dir():
        raise PotcarError(f"POTCAR library not found: {potcar_root} (set vasp.potcar_root in configs/site.yaml)")
    chunks: List[str] = []
    records: List[PotcarRecord] = []
    for element in element_order:
        label = labels.get(element)
        if label is None:
            raise PotcarError(f"No POTCAR label configured for element {element}")
        path = potcar_root / label / "POTCAR"
        if not path.is_file():
            raise PotcarError(f"POTCAR for label '{label}' not found at {path}")
        text = path.read_text(encoding="utf-8", errors="replace")
        titel, enmax = read_potcar_identity(text)
        # TITEL looks like "PAW_PBE Y_sv 06Sep2000": flavour, dataset label, date.
        tokens = titel.split() if titel else []
        if len(tokens) >= 2 and tokens[1].split("_")[0] != element:
            raise PotcarError(f"POTCAR {path} has TITEL '{titel}', which is not a dataset for element {element}")
        if tokens and not tokens[0].startswith("PAW_PBE"):
            raise PotcarError(f"POTCAR {path} is '{tokens[0]}', but this project uses PBE PAW datasets (PAW_PBE)")
        chunks.append(text if text.endswith("\n") else text + "\n")
        records.append(
            PotcarRecord(
                element=element,
                label=label,
                titel=titel,
                enmax_eV=enmax,
                sha256=hashlib.sha256(text.encode("utf-8")).hexdigest(),
                source=str(path),
            )
        )
    return "".join(chunks), records


def potcar_records_as_dicts(records: Sequence[PotcarRecord]) -> List[dict]:
    return [asdict(r) for r in records]


def encut_warnings(encut: float, records: Sequence[PotcarRecord], *, cell_relax: bool) -> List[str]:
    """Practical ENCUT sanity checks against POTCAR ENMAX values."""

    enmax_values = [r.enmax_eV for r in records if r.enmax_eV is not None]
    if not enmax_values:
        return []
    enmax = max(enmax_values)
    warnings = []
    if encut < enmax:
        warnings.append(f"ENCUT={encut} eV is below the largest POTCAR ENMAX ({enmax} eV).")
    if cell_relax and encut < 1.3 * enmax:
        warnings.append(
            f"ENCUT={encut} eV < 1.3 x ENMAX ({1.3 * enmax:.0f} eV): "
            "cell relaxation (ISIF=3) may suffer from Pulay stress."
        )
    return warnings

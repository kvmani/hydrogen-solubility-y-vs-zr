"""``hsol plan``: expand a campaign file into explicit, validated run configs.

A campaign file (``configs/campaigns/*.yaml``) describes one stage of the project
for all systems at once. Keys::

    campaign:    name; configs are written to configs/generated/<campaign>[_<tag>]/
    stage:       stage1 ... stage6 (part of every run_id)
    tag:         optional suffix appended to run_ids; bump it to re-run a stage with
                 changed physics without overwriting earlier results
    description: free text
    include:     files (relative to the campaign) whose ``defaults`` are merged in
                 first -- used for settings that must be identical across stages
    defaults:    settings shared by all runs (structure/vasp/potcars/hpc/notes)
    systems:     per-system settings merged over defaults, e.g. {Y: {...}, Zr: {...}}
    runs:        list of runs created once per system (``systems: [Y]`` restricts)
    shared_runs: list of runs created once, with an explicit ``system`` (e.g. H2)
    sweeps:      convergence helper: {calc_type, encut_eV: [...], kpoint_spacing: [...]}

Merge order (later wins): defaults -> systems[<system>] -> run entry. Mappings are
merged key by key, lists are replaced; ``null`` clears an inherited value.
``{system}`` in any string is replaced by the system name (e.g.
``lattice_from_run: "{system}_stage1_relax"``). run_id =
``<system>_<stage>_<label>[_<tag>]``.

Values written as ``"<...>"`` are placeholders: planning stops and lists them until
they are filled in. Every generated config is validated before anything is written,
so a typo in a campaign file never produces a half-written plan.
"""

from __future__ import annotations

import copy
import csv
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

import yaml

from .config_models import SCHEMA_VERSION, ConfigValidationError, RunConfig, load_mapping, parse_run_config
from .paths import GENERATED_CONFIGS_DIR, display_path
from .provenance import utc_now

GENERATED_MARKER = "# Generated by `hsol plan`"
CAMPAIGN_KEYS = {
    "campaign",
    "stage",
    "tag",
    "description",
    "include",
    "defaults",
    "systems",
    "runs",
    "shared_runs",
    "sweeps",
}
RUN_KEYS = {"label", "calc_type", "objective", "structure", "vasp", "potcars", "hpc", "notes", "systems", "system"}
SETTING_KEYS = {"structure", "vasp", "potcars", "hpc", "notes"}


class PlanError(ValueError):
    """Raised for malformed campaign files."""


@dataclass
class PlannedRun:
    config: RunConfig
    payload: Dict[str, Any]


def deep_merge(base: Dict[str, Any], override: Dict[str, Any]) -> Dict[str, Any]:
    """Recursively merge mappings; non-mapping values in ``override`` replace ``base``."""

    merged = copy.deepcopy(base)
    for key, value in (override or {}).items():
        if isinstance(value, dict) and isinstance(merged.get(key), dict):
            merged[key] = deep_merge(merged[key], value)
        else:
            merged[key] = copy.deepcopy(value)
    return merged


def substitute_system(value: Any, system: str) -> Any:
    """Replace ``{system}`` in every string inside ``value`` (e.g. ``{system}_stage1_relax``)."""

    if isinstance(value, str):
        return value.replace("{system}", system)
    if isinstance(value, dict):
        return {k: substitute_system(v, system) for k, v in value.items()}
    if isinstance(value, list):
        return [substitute_system(v, system) for v in value]
    return value


def find_placeholders(value: Any, prefix: str = "") -> List[str]:
    """Paths of string values that are still template markers such as ``"<ENCUT>"``."""

    if isinstance(value, str):
        text = value.strip()
        return [f"{prefix} = {text}"] if text.startswith("<") and text.endswith(">") else []
    if isinstance(value, dict):
        return [p for k, v in value.items() for p in find_placeholders(v, f"{prefix}.{k}" if prefix else str(k))]
    if isinstance(value, list):
        return [p for i, v in enumerate(value) for p in find_placeholders(v, f"{prefix}[{i}]")]
    return []


def load_campaign(path: Path) -> Dict[str, Any]:
    """Read a campaign file and merge its ``include`` files (paths relative to it) underneath.

    Included files may only contain ``defaults``; the including campaign's own
    ``defaults`` win on conflicts.
    """

    campaign = load_mapping(path)
    merged_defaults: Dict[str, Any] = {}
    for rel in campaign.get("include") or []:
        inc_path = (path.parent / rel).resolve()
        included = load_mapping(inc_path)
        if set(included) - {"defaults"}:
            raise PlanError(f"{display_path(inc_path)}: include files may only contain 'defaults'")
        merged_defaults = deep_merge(merged_defaults, included.get("defaults") or {})
    campaign["defaults"] = deep_merge(merged_defaults, campaign.get("defaults") or {})
    return campaign


def _settings(mapping: Dict[str, Any], where: str) -> Dict[str, Any]:
    unknown = set(mapping) - SETTING_KEYS
    if unknown:
        raise PlanError(f"{where}: unknown keys {sorted(unknown)} (allowed: {sorted(SETTING_KEYS)})")
    return mapping


def _kgrid_tag(grid: List[int]) -> str:
    return "x".join(str(int(g)) for g in grid)


def _kpoints_text(config: RunConfig) -> str:
    k = config.vasp.kpoints
    return _kgrid_tag(list(k.grid)) if k.grid is not None else f"spacing {k.spacing}"


def _encut_tag(value: float) -> str:
    return str(int(value)) if float(value).is_integer() else str(value).replace(".", "p")


def _sweep_entries(sweeps: Dict[str, Any], base: Dict[str, Any]) -> List[Dict[str, Any]]:
    """Run entries for an ENCUT / k-point-spacing convergence sweep around the base point.

    The base point (base ENCUT + base k-point spacing) is generated once, labelled
    ``ref`` and belongs to both series; the other points vary one parameter at a
    time. Sweeping the *spacing* (not explicit grids) means the converged value is
    exactly the rule later used for supercells and hydrides.
    """

    unknown = set(sweeps) - {"calc_type", "encut_eV", "kpoint_spacing"}
    if unknown:
        raise PlanError(f"sweeps: unknown keys {sorted(unknown)} (allowed: calc_type, encut_eV, kpoint_spacing)")
    calc_type = sweeps.get("calc_type", "host_convergence")
    try:
        base_encut = float(base["vasp"]["incar"]["ENCUT"])
        base_spacing = float(base["vasp"]["kpoints"]["spacing"])
    except (KeyError, TypeError, ValueError) as exc:
        raise PlanError("sweeps need numeric defaults.vasp.incar.ENCUT and defaults.vasp.kpoints.spacing") from exc

    def entry(label: str, parameter: str, value: str, encut: float, spacing: float, what: str) -> Dict[str, Any]:
        encut_value = int(encut) if float(encut).is_integer() else encut
        return {
            "label": label,
            "calc_type": calc_type,
            "objective": f"Stage-1 {what} for alpha-{{system}}: ENCUT={encut:g} eV, k-spacing {spacing:g} 1/A.",
            "vasp": {"incar": {"ENCUT": encut_value}, "kpoints": {"spacing": spacing, "grid": None}},
            "_sweep": {"parameter": parameter, "value": value},
        }

    entries = [
        entry(
            "ref",
            "reference",
            f"{_encut_tag(base_encut)}/{base_spacing:g}",
            base_encut,
            base_spacing,
            "convergence reference point",
        )
    ]
    for encut in sweeps.get("encut_eV", []):
        if float(encut) != base_encut:
            entries.append(
                entry(
                    f"encut{_encut_tag(encut)}",
                    "encut",
                    _encut_tag(encut),
                    float(encut),
                    base_spacing,
                    "ENCUT convergence point",
                )
            )
    for spacing in sweeps.get("kpoint_spacing", []):
        if float(spacing) != base_spacing:
            entries.append(
                entry(
                    f"kspacing{float(spacing):g}",
                    "kpoints",
                    f"{float(spacing):g}",
                    base_encut,
                    float(spacing),
                    "k-point convergence point",
                )
            )
    return entries


def _build_payload(
    campaign: Dict[str, Any], system: str, entry: Dict[str, Any], settings: Dict[str, Any]
) -> Dict[str, Any]:
    stage = campaign["stage"]
    tag = campaign.get("tag")
    label = entry.get("label")
    if not label:
        raise PlanError(f"a run entry has no label: {entry}")
    run_id = f"{system}_{stage}_{label}" + (f"_{tag}" if tag else "")
    run_section: Dict[str, Any] = {
        "run_id": run_id,
        "stage": stage,
        "system": system,
        "calc_type": entry.get("calc_type"),
        "objective": str(entry.get("objective", "")).replace("{system}", system),
        "campaign": campaign["campaign"],
        "notes": list(settings.pop("notes", [])) + list(entry.get("notes", [])),
    }
    if "_sweep" in entry:
        run_section["sweep"] = entry["_sweep"]
    ordered = {k: settings[k] for k in ("structure", "vasp", "potcars", "hpc") if k in settings}
    return {"schema_version": SCHEMA_VERSION, "run": run_section, **ordered}


def expand_campaign(campaign: Dict[str, Any], *, origin: str = "<campaign>") -> List[PlannedRun]:
    """Expand a campaign mapping into validated run configs (nothing is written)."""

    unknown = set(campaign) - CAMPAIGN_KEYS
    if unknown:
        raise PlanError(f"{origin}: unknown top-level keys {sorted(unknown)}")
    for required in ("campaign", "stage"):
        if not campaign.get(required):
            raise PlanError(f"{origin}: '{required}' is required")

    defaults = _settings(campaign.get("defaults") or {}, "defaults")
    systems: Dict[str, Any] = campaign.get("systems") or {}
    per_system = list(campaign.get("runs") or [])
    if campaign.get("sweeps"):
        per_system = _sweep_entries(campaign["sweeps"], defaults) + per_system

    for entry in per_system:
        if set(entry) - RUN_KEYS - {"_sweep"}:
            raise PlanError(f"run '{entry.get('label')}': unknown keys {sorted(set(entry) - RUN_KEYS - {'_sweep'})}")
        if "system" in entry:
            raise PlanError(f"run '{entry.get('label')}': use 'systems: [...]' in runs, 'system:' only in shared_runs")
        for system in entry.get("systems") or []:
            if system not in systems:
                raise PlanError(f"run '{entry.get('label')}' targets system '{system}' missing from 'systems'")
    if per_system and not systems:
        raise PlanError(f"{origin}: per-system runs need a 'systems' section")

    # System-major order: all runs of the first system, then the next, then shared runs.
    jobs: List[Tuple[str, Dict[str, Any], Dict[str, Any]]] = []
    for system, system_settings in systems.items():
        base = deep_merge(defaults, _settings(system_settings or {}, f"systems.{system}"))
        for entry in per_system:
            if system in (entry.get("systems") or list(systems)):
                jobs.append((system, entry, base))
    for entry in campaign.get("shared_runs") or []:
        if set(entry) - RUN_KEYS:
            raise PlanError(f"shared run '{entry.get('label')}': unknown keys {sorted(set(entry) - RUN_KEYS)}")
        if not entry.get("system"):
            raise PlanError(f"shared run '{entry.get('label')}' needs an explicit 'system'")
        jobs.append((entry["system"], entry, copy.deepcopy(defaults)))

    planned: List[PlannedRun] = []
    seen = set()
    for system, entry, base in jobs:
        settings = deep_merge(base, {k: entry[k] for k in ("structure", "vasp", "potcars", "hpc") if k in entry})
        payload = substitute_system(_build_payload(campaign, system, entry, settings), system)
        unfilled = find_placeholders(payload)
        if unfilled:
            raise PlanError(
                f"{origin}: run {payload['run']['run_id']} still has placeholder values - fill them in first "
                "(converged values come from `hsol analyze convergence`):\n  " + "\n  ".join(unfilled)
            )
        run_id = payload["run"]["run_id"]
        if run_id in seen:
            raise PlanError(f"{origin}: duplicate run_id {run_id}")
        seen.add(run_id)
        try:
            config = parse_run_config(payload, origin=f"{origin} -> {run_id}")
        except ConfigValidationError as exc:
            raise PlanError(str(exc)) from exc
        planned.append(PlannedRun(config, payload))
    if not planned:
        raise PlanError(f"{origin}: the campaign defines no runs")
    return planned


class _ConfigDumper(yaml.SafeDumper):
    """Block-style mappings with short scalar lists inline: ``grid: [16, 16, 10]``."""


def _represent_list(dumper: yaml.SafeDumper, data: list) -> yaml.Node:
    flow = all(not isinstance(v, (dict, list)) for v in data)
    return dumper.represent_sequence("tag:yaml.org,2002:seq", data, flow_style=flow)


_ConfigDumper.add_representer(list, _represent_list)


def dump_yaml(payload: Dict[str, Any]) -> str:
    return yaml.dump(payload, Dumper=_ConfigDumper, sort_keys=False, default_flow_style=False, width=110)


def output_dir_for(campaign: Dict[str, Any]) -> Path:
    name = campaign["campaign"] + (f"_{campaign['tag']}" if campaign.get("tag") else "")
    return GENERATED_CONFIGS_DIR / name


def write_plan(campaign_path: Path, output_dir: Optional[Path] = None) -> Tuple[Path, List[PlannedRun], List[Path]]:
    """Expand ``campaign_path`` and write one YAML per run plus ``plan.csv``.

    Returns (output directory, planned runs, removed stale configs). Stale configs
    are files previously generated into the same directory that the campaign no
    longer defines; they are removed so ``hsol prepare <dir>`` never picks them up.
    """

    campaign = load_campaign(campaign_path)
    planned = expand_campaign(campaign, origin=display_path(campaign_path))
    out = output_dir or output_dir_for(campaign)
    out.mkdir(parents=True, exist_ok=True)

    header = (
        f"{GENERATED_MARKER} from {display_path(campaign_path)} at {utc_now()}.\n"
        "# Do not edit: change the campaign file and run `hsol plan` again.\n"
    )
    wanted = set()
    for item in planned:
        path = out / f"{item.config.run_id}.yaml"
        wanted.add(path)
        path.write_text(header + dump_yaml(item.payload), encoding="utf-8")

    removed = []
    for path in sorted(out.glob("*.yaml")):
        if path not in wanted and path.read_text(encoding="utf-8").startswith(GENERATED_MARKER):
            path.unlink()
            removed.append(path)

    with (out / "plan.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle)
        writer.writerow(["run_id", "system", "calc_type", "depends_on", "encut_eV", "kpoints", "objective"])
        for item in planned:
            c = item.config
            writer.writerow(
                [
                    c.run_id,
                    c.run.system,
                    c.run.calc_type,
                    " ".join(c.dependencies()),
                    c.vasp.incar["ENCUT"],
                    _kpoints_text(c),
                    c.run.objective,
                ]
            )
    return out, planned, removed
